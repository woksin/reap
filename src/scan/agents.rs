    #[test]
    fn no_two_rules_name_the_same_path() {
        // Two rules on one path report the same bytes twice, and the figure at
        // the top of the screen is the number people act on.
        let mut paths: Vec<&str> = SCRATCH
            .iter()
            .map(|(p, ..)| *p)
            .chain(SESSIONS.iter().map(|(p, ..)| *p))
            .collect();
        paths.sort_unstable();
        let before = paths.len();
        paths.dedup();
        assert_eq!(paths.len(), before, "an agent path is listed twice");
    }

