//! What the coding agents leave behind.
//!
//! Every other scanner here predates the thing this one exists for. A machine
//! that runs agents accumulates a second kind of debris beside the build
//! output: transcripts of every conversation, snapshots taken before every
//! edit, logs of every background run, and a package tree per tool. It lands in
//! dot-directories directly under `$HOME` — `~/.claude`, `~/.codex`, `~/.pi` —
//! which is the one place nothing else looks. Not the platform cache root, not
//! the application-support sweep, not the repository walk.
//!
//! The split that matters is inside those directories rather than between them.
//! A tool's `cache` and its finished job logs are regenerated by using it. Its
//! downloaded packages cost a re-download. Its session transcripts are the only
//! record that a piece of work happened at all, and no amount of re-running
//! brings one back — so they are offered the way `Personal` offers a download:
//! visible, one row per project, aged individually, and irreversible.
//!
//! A path this machine does not have is a rule that does not apply, which is
//! how one table covers every tool without asking which are installed. The
//! directories are rules like any other and take `[[agent]]` entries from the
//! configuration; the session *layouts* below stay in code, because a layout is
//! a scheme rather than a path and a configuration key naming one reap has not
//! been taught to read would produce rows it cannot label. A store named by a
//! configured rule is offered whole, which is the honest thing for a shape
//! nothing here understands.

