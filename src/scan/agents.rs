    #[test]
    fn no_rule_nests_inside_another() {
        // The same bytes under two labels, with two different risks, and a
        // headline figure that counts them both. Worse here than elsewhere: the
        // two labels would disagree about whether the bytes are safe.
        for outer in every_path() {
            for inner in every_path() {
                assert!(
                    !inner.starts_with(&format!("{outer}/")),
                    "{inner} sits inside {outer}"
                );
            }
        }
    }

    #[test]
    fn no_rule_names_a_tools_top_level_directory() {
        // `~/.claude` holds settings, credentials and the record of what is
        // installed. Nothing that takes a whole tool's directory can be
        // describing one kind of thing, so this much is checkable from the
        // shape of the path alone.
        //
        // Only this much. Whether a directory *further* in mixes state with
        // content is a fact about that tool rather than about its path, and the
        // test below carries the cases where that was found to be true.
        for path in every_path() {
            let depth = path.trim_start_matches("~/").split('/').count();
            assert!(
                depth >= 2,
                "{path} names a tool's whole directory rather than one thing inside it"
            );
        }
    }

    #[test]
    fn the_rules_that_had_to_be_narrowed_stay_narrow() {
        // Each of these named the parent once, and each of those parents keeps
        // its bookkeeping beside the content it was named for:
        //
        //   ~/.pi/agent/npm      package.json — the list of your extensions,
        //                        and the thing that reinstalls them
        //   ~/.claude/plugins    installed_plugins.json, known_marketplaces.json
        //   ~/.codex/plugins     the same, for Codex
        //
        // Taking the parent frees the same bytes and quietly loses the record
        // of what you had, while the row calls itself a cache. Nothing about
        // the shape of those paths says so, so it is written down here: a
        // reader widening one of these has to delete a test that explains why
        // it is the way it is.
        for (parent, named) in [
            ("~/.pi/agent/npm", "~/.pi/agent/npm/node_modules"),
            ("~/.claude/plugins", "~/.claude/plugins/cache"),
            ("~/.codex/plugins", "~/.codex/plugins/cache"),
        ] {
            assert!(
                every_path().contains(&named),
                "{named} is no longer named by any rule"
            );
            assert!(
                !every_path().contains(&parent),
                "{parent} keeps its own bookkeeping beside the content — name {named}"
            );
        }
    }

    #[test]
    fn anything_holding_history_is_graded_irreversible() {
        // The safe tier is what `s` and the quick recipes take without asking,
        // so a transcript landing there is the one mistake this file must not
        // make. Matched on the path rather than on the grading, so a rule added
        // later is checked against what it names rather than against what
        // whoever added it believed.
        // "projects" is deliberately not among these. It describes a layout —
        // one directory per project — and says nothing about what is in them:
        // `~/.claude/projects` holds transcripts, `~/.pi-lens/projects` holds
        // search indexes that are rebuilt by re-reading the code. A guard that
        // cannot tell those apart would force the wrong grading onto whichever
        // one it met second, which is a test dictating a false fact rather than
        // catching one.
        for (path, _, label, _, risk) in SCRATCH {
            let holds_history = ["session", "history", "storage", "state"]
                .iter()
                .any(|word| path.contains(word));
            assert!(
                !holds_history || *risk == RiskName::Irreversible,
                "{label} ({path}) keeps history and is graded {risk:?}"
            );
        }
        // And every session store, whatever it is called, is graded in code
        // rather than in the table — which is what this asserts about the
        // table: none of them is in it.
        for (path, tool, _) in SESSIONS {
            assert!(
                !SCRATCH.iter().any(|(p, ..)| p == path),
                "{tool}'s store at {path} is graded twice"
            );
        }
    }
